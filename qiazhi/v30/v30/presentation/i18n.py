REQUIRED_BAZI_TERM_KEYS = tuple(BAZI_TERMS["zh"].keys())


def label(locale: str, key: str) -> str:
    labels = LABELS.get(locale, LABELS["zh"])  # type: ignore[arg-type]
    return labels.get(key, LABELS["zh"].get(key, key))


def term_label(locale: str, key: str) -> str:
    terms = BAZI_TERMS.get(locale, BAZI_TERMS["zh"])  # type: ignore[arg-type]
    return terms.get(key, BAZI_TERMS["zh"].get(key, key))


def build_locale_terminology_contract(locale: str) -> dict[str, object]:
    resolved = locale if locale in BAZI_TERMS else "zh"
    terms = BAZI_TERMS[resolved]  # type: ignore[index]
    missing = [key for key in REQUIRED_BAZI_TERM_KEYS if key not in terms]
    fallback = [key for key in REQUIRED_BAZI_TERM_KEYS if term_label(resolved, key) == key]
    return {
        "version": "v30.locale_terminology_contract.v1",
        "locale": resolved,
        "term_count": len(terms),
        "required_term_count": len(REQUIRED_BAZI_TERM_KEYS),
        "missing_term_keys": missing,
        "fallback_term_keys": fallback,
        "ready": not missing and not fallback,
        "boundary": "locale_terms_render_bazi_language_without_creating_chart_facts",
    }

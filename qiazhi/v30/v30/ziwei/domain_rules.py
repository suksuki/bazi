def _rule(
    rule_id: str,
    domain: ZiweiDomainKey,
    condition: str,
    claim_key: str,
    probe_trigger: str,
    *,
    palace_refs: list[str],
    transform_refs: list[str] | None = None,
    related_palaces: list[str] | None = None,
    star_refs: list[str] | None = None,
    claim: str,
    strength: float = 0.58,
    hidden: list[str] | None = None,
) -> ZiweiDomainRule:
    return ZiweiDomainRule(
        rule_id=rule_id,
        domain=domain,
        condition=condition,
        palace_refs=palace_refs,
        star_refs=star_refs or [],
        transform_refs=transform_refs or [],
        related_palaces=related_palaces or [],
        claim=claim,
        claim_key=claim_key,
        probe_trigger=probe_trigger,
        polarity=SignalPolarity.SUPPORT,
        strength_hint=strength,
        confidence_hint=min(0.72, strength + 0.04),
        assertion_level_hint=AssertionLevelHint.WEAK_CANDIDATE,
        target_hidden_attributes=hidden or [],
    )



def rules_by_domain(domain: ZiweiDomainKey) -> list[ZiweiDomainRule]:
    return [rule for rule in ZIWEI_V1_DOMAIN_RULES if rule.domain == domain]


def rule_domain_counts() -> dict[str, int]:
    return dict(Counter(rule.domain for rule in ZIWEI_V1_DOMAIN_RULES))

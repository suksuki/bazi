export function normalizeAppLanguage(value: unknown): AppLanguage {
  return value === "en" || value === "ko" ? value : "zh";
}

export function t(lang: AppLanguage, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] || DICTS.zh;
  const template = dict[key] || DICTS.zh[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(vars?.[token] ?? `{${token}}`));
}

export function translateTerm(lang: AppLanguage, value: string): string {
  const raw = String(value || "").trim();
  if (!raw) return raw;
  if (TEN_GOD_MAP[raw]) return TEN_GOD_MAP[raw][lang];
  if (GENERIC_TERM_MAP[raw]) return GENERIC_TERM_MAP[raw][lang];
  return raw;
}

export function translateTermList(lang: AppLanguage, values: string[], separator = " / "): string {
  return values.map((value) => translateTerm(lang, value)).join(separator);
}
